# print() mostra uma mensagem na tela.
print("Olá! Estou começando a programar em Python.")

# Uma variável guarda um valor para usarmos mais tarde.
nome = "Israel"
linguagem = "Python 3"

# O f antes das aspas permite colocar variáveis dentro do texto.
print(f"{nome} está aprendendo {linguagem}.")

cidade = input('Digite o nome de sua cidade: ')

print(f'{nome} mora em {cidade} e está aprendendo {linguagem}.')    

